-- ====================================================================
-- SUPABASE SCHEMA FOR PHYSIO MONITOR (SINGLE CONSOLIDATED TABLE)
-- Jalankan skrip ini di SQL Editor Supabase Dashboard Anda.
-- ====================================================================

-- Hapus tabel lama jika ingin memulai dari awal yang bersih
DROP TABLE IF EXISTS physio_records CASCADE;

-- Tabel Tunggal: Menyimpan Data Sensor + Keputusan Model + Respon Aktuator AUTO
CREATE TABLE IF NOT EXISTS physio_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ts TIMESTAMPTZ NOT NULL,
    device_id TEXT NOT NULL DEFAULT 'esp32-01',

    -- 1. Data Hasil Pembacaan Sensor
    hr FLOAT,                     -- Detak Jantung (BPM)
    spo2 FLOAT,                   -- Saturasi Oksigen (%)
    temp FLOAT,                   -- Suhu Tubuh (°C)
    hum FLOAT,                    -- Kelembapan Ruangan (%)
    room_temp FLOAT,              -- Suhu Ruangan (°C)

    -- 2. Hasil Keputusan Model AI & Rules
    label TEXT NOT NULL,          -- 'NORMAL' atau 'ANOMALY'
    severity INT NOT NULL,        -- 0 = Normal, 1 = Warning, 2 = Anomali Kritis
    ml_score FLOAT,               -- Skor Anomali dari model Machine Learning

    -- 3. Aktivitas Aktuator Secara AUTO (Hasil langsung dari keputusan model)
    led_color TEXT NOT NULL,      -- 'GREEN', 'YELLOW', atau 'RED'
    buzzer_active BOOLEAN NOT NULL -- TRUE jika buzzer berbunyi (alarm), FALSE jika mati
);

-- Indeks untuk mempercepat pencarian dan visualisasi data
CREATE INDEX IF NOT EXISTS idx_physio_records_ts ON physio_records (device_id, ts DESC);
CREATE INDEX IF NOT EXISTS idx_physio_records_label ON physio_records (label);
